-- Session restoration, matching omarchy/LazyVim. Sessions are saved
-- automatically on exit and restored on demand:
--   <leader>qs  restore session for the current dir
--   <leader>ql  restore the last session
--   <leader>qd  don't save the current session
return {
	"folke/persistence.nvim",
	event = "BufReadPre",
	opts = {},
	keys = {
		{
			"<leader>qs",
			function()
				require("persistence").load()
			end,
			desc = "Restore Session",
		},
		{
			"<leader>ql",
			function()
				require("persistence").load({ last = true })
			end,
			desc = "Restore Last Session",
		},
		{
			"<leader>qd",
			function()
				require("persistence").stop()
			end,
			desc = "Don't Save Current Session",
		},
	},
}